// Generates a one-time SQL seed that loads the sensitive leader data into the
// `leader_content` table (single jsonb row, RLS-protected). Run after
// `npm run parse:leader` so the SQL matches the latest leader.json.
//
//   node scripts/make-leader-seed.mjs
//
// Then paste scripts/seed-leader.sql into the Supabase SQL editor once (or
// whenever the leader data changes). The data never ships in the client bundle.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const IN = join(here, '..', 'src', 'data', 'leader.json');
const OUT = join(here, 'seed-leader.sql');

const payload = readFileSync(IN, 'utf8').trim();
// Escape single quotes for a SQL string literal.
const escaped = payload.replace(/'/g, "''");

const sql = `-- Auto-generated by scripts/make-leader-seed.mjs — do not edit by hand.
-- One-time seed of the sensitive leader data into the RLS-protected table.
-- Paste into the Supabase SQL editor and Run. Safe to re-run (upsert).

insert into public.leader_content (id, payload, updated_at)
values (1, '${escaped}'::jsonb, now())
on conflict (id) do update
  set payload = excluded.payload,
      updated_at = now();
`;

writeFileSync(OUT, sql);
console.log(`Wrote ${OUT} (${(sql.length / 1024).toFixed(1)} KB)`);
